def verdicts(s1="delivered-verified", s2="delivered-verified", sup2=0.0, unver=0.0, lands=0.0,
             req2=0.9, esc1=False):
    return {"req_1": V(0.9), "sup_1": V(0.0), "state_1": V(s1, escalate=esc1),
            "req_2": V(req2), "sup_2": V(sup2), "state_2": V(s2),
            "unverified_claim": V(unver), "lands_on_user": V(lands)}


class Combine(unittest.TestCase):
    def test_all_verified_done(self):
        r = wv.combine(ASKS, verdicts(), "DONE")
        self.assertEqual((r["computed"], r["consistent"]), ("DONE", True))

    def test_decision_asks_never_judged(self):
        self.assertNotIn("req_3", {q["id"] for q in wv.questions(ASKS)})
        self.assertEqual([a["n"] for a in wv.combine(ASKS, verdicts(), "DONE")["asks"]], [1, 2])

    def test_one_partial_downgrades_done_claim(self):
        r = wv.combine(ASKS, verdicts(s2="partial"), "DONE")
        self.assertEqual((r["computed"], r["consistent"]), ("PARTIAL", False))
        self.assertIn("#2 partial", r["reasons"])

    def test_superseded_ask_ignored(self):
        r = wv.combine(ASKS, verdicts(s2="not-started", sup2=0.9), "DONE")
        self.assertEqual(r["computed"], "DONE")

    def test_non_request_ignored(self):
        r = wv.combine(ASKS, verdicts(s2="not-started", req2=0.1), "DONE")
        self.assertEqual(r["computed"], "DONE")

    def test_unverified_claim_blocks_done(self):
        r = wv.combine(ASKS, verdicts(unver=0.8), "DONE")
        self.assertEqual(r["computed"], "PARTIAL")

    def test_lands_on_user_is_blocked(self):
        r = wv.combine(ASKS, verdicts(lands=0.9), "DONE")
        self.assertEqual((r["computed"], r["consistent"]), ("BLOCKED", False))
        r = wv.combine(ASKS, verdicts(lands=0.9), "BLOCKED")
        self.assertTrue(r["consistent"])

    def test_escalated_state_never_done_never_downgrades(self):
        # unsure is surfaced for a human, not treated as a gap
        r = wv.combine(ASKS, verdicts(esc1=True), "DONE")
        self.assertEqual((r["computed"], r["consistent"]), ("UNCLEAR", True))
        self.assertIn("#1", r["unsure"])
        self.assertFalse(r["asks"][0]["sure"])

    def test_escalated_gap_state_does_not_fire(self):
        v = verdicts(s1="not-started", esc1=True)
        self.assertEqual(wv.combine(ASKS, v, "DONE")["computed"], "UNCLEAR")

    def test_confident_unverified_delivery_is_a_gap(self):
        r = wv.combine(ASKS, verdicts(s2="delivered-unverified"), "DONE")
        self.assertEqual(r["computed"], "PARTIAL")

    def test_escalated_flags_listed_not_applied(self):
        v = verdicts() | {"unverified_claim": V(0.9, escalate=True),
                          "lands_on_user": V(0.9, escalate=True)}
        r = wv.combine(ASKS, v, "DONE")
        self.assertEqual(r["computed"], "DONE")
        self.assertEqual(set(r["unsure"]), {"unverified_claim", "lands_on_user"})

    def test_judge_reads_claim_when_no_status_word(self):
        v = verdicts(s2="partial") | {"claimed_j": V("DONE")}
        r = wv.combine(ASKS, v, "none")
        self.assertEqual((r["claimed"], r["claimed_source"], r["consistent"]),
                         ("DONE", "judge-read", False))
        # an escalated read does not count
        v["claimed_j"] = V("DONE", escalate=True)
        self.assertEqual(wv.combine(ASKS, v, "none")["claimed"], "none")

    def test_completeness_recorded(self):
        r = wv.combine(ASKS, verdicts() | {"completeness": V(3.4)}, "DONE")
        self.assertEqual(r["completeness"], 3.4)

    def test_question_battery_shape(self):
        ids = [q["id"] for q in wv.questions(ASKS)]
        self.assertEqual(ids[-4:], ["unverified_claim", "lands_on_user", "claimed_j", "completeness"])
        score = [q for q in wv.questions(ASKS) if q["id"] == "completeness"][0]
        self.assertEqual(len(score["levels"]), 5)

    def test_verdict_shape_check(self):
        qs = wv.questions(ASKS)
        answer = {"yes_no": lambda q: 0.2, "choice": lambda q: list(q["options"])[0],
                  "score": lambda q: 2.5}
        good = {q["id"]: V(answer[q["type"]](q)) for q in qs}
        ok = lambda vs: wv.bad_verdicts(qs, {"verdicts": list(vs)})
        self.assertEqual(ok(dict(v, id=k) for k, v in good.items()), ([], []))
        # an escalated verdict that never reached the judge carries answer null: well-formed
        esc = [dict(v, id=k) for k, v in good.items()]
        esc[0] = {"id": esc[0]["id"], "answer": None, "escalate": True, "confidence": 0}
        self.assertEqual(ok(esc), ([], []))
        bad = [dict(v, id=k) for k, v in good.items()]
        bad[0]["answer"] = None                          # not escalated, no answer
        bad[1]["answer"] = 1.5                           # P(yes) outside [0, 1]
        bad[2] = "not a verdict"                         # state_1's slot, not a dict
        self.assertEqual(ok(bad), (["state_1"], ["req_1", "sup_1"]))
        self.assertEqual(wv.bad_verdicts(qs, {"verdicts": "nope"})[0], [q["id"] for q in qs])
        self.assertEqual(wv.bad_verdicts(qs, ["not", "an", "object"])[0], [q["id"] for q in qs])

    def test_underclaim_is_consistent(self):
        # The judge only downgrades: claiming PARTIAL when computed DONE is fine
        self.assertTrue(wv.combine(ASKS, verdicts(), "PARTIAL")["consistent"])

    def test_missing_status_word_inconsistent(self):
        r = wv.combine(ASKS, verdicts(), "none")
        self.assertFalse(r["consistent"])

    def test_no_active_requests(self):
        r = wv.combine(ASKS, verdicts(req2=0.1) | {"req_1": V(0.1)}, "DONE")
        self.assertEqual((r["computed"], r["consistent"]), ("n/a", True))


class EndToEnd(unittest.TestCase):
    """Runs the CLI with a fake judge and a fake redactor."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.fake, self.redactor = write_fakes(self.tmp)
        self.capture = os.path.join(self.tmp, "req.json")
        self.ev = {"session_id": "S1", "report": "DONE — built A",
                   "asks": [{"i": 1, "channel": "prompt", "text": "build A for SECRETCLIENT"}],
                   "repos": []}

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def run_cli(self, *args, **env):
        e = clean_env(JUDGE_CMD=f"{sys.executable} {self.fake}", JUDGE_REDACT=self.redactor,
                      CAPTURE=self.capture)
        e.update(env)
        return subprocess.run([sys.executable, os.path.join(BIN, "wrap_verdict.py"), "--no-log",
                               *args], input=json.dumps(self.ev), capture_output=True, text=True,
                              env=e)

    def test_consistent_exit0_and_state_redacted(self):
        r = self.run_cli()
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(json.loads(r.stdout)["computed"], "DONE")
        sent = read(self.capture)
        self.assertNotIn("SECRETCLIENT", sent)
        self.assertIn("<client>", sent)

    def test_overclaim_exit1(self):
        r = self.run_cli(STATE="partial")
        self.assertEqual(r.returncode, 1)
        self.assertEqual(json.loads(r.stdout)["computed"], "PARTIAL")

    def test_report_file_overrides(self):
        rp = os.path.join(self.tmp, "report.md")
        with open(rp, "w") as f:
            f.write("PARTIAL — B remains\n")
        r = self.run_cli("--report", rp, STATE="partial")
        self.assertEqual(r.returncode, 0)

    def test_judge_failure_is_advisory_exit3(self):
        r = self.run_cli(FAKE_MODE="fail")
        self.assertEqual(r.returncode, 3)
        self.assertIsNone(json.loads(r.stdout)["computed"])

    def test_judge_exit3_escalated_is_a_result_not_an_error(self):
        r = self.run_cli(FAKE_MODE="escalated")
        self.assertEqual(r.returncode, 0, r.stdout)
        self.assertEqual(json.loads(r.stdout)["computed"], "DONE")

    def test_judge_unreachable_is_advisory_exit3(self):
        self.assertEqual(self.run_cli(FAKE_MODE="down").returncode, 3)

    def test_no_judge_configured_is_advisory_exit3(self):
        e = clean_env(JUDGE_REDACT=self.redactor, CAPTURE=self.capture)
        r = subprocess.run([sys.executable, os.path.join(BIN, "wrap_verdict.py"), "--no-log"],
                           input=json.dumps(self.ev), capture_output=True, text=True, env=e)
        self.assertEqual(r.returncode, 3, r.stderr)
        out = json.loads(r.stdout)
        self.assertIsNone(out["computed"])
        self.assertIn("JUDGE_CMD", out["advisory"])
        self.assertFalse(os.path.exists(self.capture))

    def test_redactor_unset_sends_unredacted_row_says_false(self):
        # redactor is optional: unset sends the state unredacted (key shapes still refused)
        log = os.path.join(self.tmp, "l.jsonl")
        e = clean_env(JUDGE_CMD=f"{sys.executable} {self.fake}", CAPTURE=self.capture)
        r = subprocess.run([sys.executable, os.path.join(BIN, "wrap_verdict.py"), "--log", log],
                           input=json.dumps(self.ev), capture_output=True, text=True, env=e)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("SECRETCLIENT", read(self.capture))
        self.assertIs(json.loads(read(log).strip())["redacted"], False)
        self.assertIs(json.loads(r.stdout)["redacted"], False)

    def test_redactor_path_missing_sends_unredacted(self):
        r = self.run_cli(JUDGE_REDACT=os.path.join(self.tmp, "nonexistent.py"))
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("SECRETCLIENT", read(self.capture))
        self.assertIs(json.loads(r.stdout)["redacted"], False)
        self.assertIn("unredacted", r.stderr)

    def test_redactor_refusal_still_sends_nothing(self):
        # when a redactor IS configured and present, it stays fail-closed
        refuser = os.path.join(self.tmp, "refuse.py")
        with open(refuser, "w") as f:
            f.write("import sys; sys.exit(2)\n")
        r = self.run_cli(JUDGE_REDACT=refuser)
        self.assertEqual(r.returncode, 3)
        self.assertIn("refused", json.loads(r.stdout)["advisory"])
        self.assertFalse(os.path.exists(self.capture))

    def test_key_shaped_state_refused_exit2(self):
        self.ev["asks"][0]["text"] += " key " + fake_key()
        r = self.run_cli()
        self.assertEqual(r.returncode, 2)
        self.assertEqual(r.stdout, "")
        self.assertFalse(os.path.exists(self.capture))
        self.assertNotIn(fake_key(), r.stderr)
        self.assertIn("key-shaped", r.stderr)

    def test_key_removed_by_redactor_is_sent(self):
        # the refusal checks what would be SENT: a redactor that strips the key clears it
        stripper = os.path.join(self.tmp, "strip.py")
        with open(stripper, "w") as f:
            f.write("import re,sys; sys.stdout.write(re.sub(r'sk-ant-[A-Za-z0-9_-]+', "
                    "'<secret>', sys.stdin.read()))\n")
        self.ev["asks"][0]["text"] += " key " + fake_key()
        r = self.run_cli(JUDGE_REDACT=stripper)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertNotIn(fake_key(), read(self.capture))
        self.assertIs(json.loads(r.stdout)["redacted"], True)

    def test_empty_verdicts_list_is_bad_input_exit2(self):
        # {"verdicts": []} used to reach combine() as "no active request" -> n/a -> DONE passes
        r = self.run_cli(FAKE_MODE="empty")
        self.assertEqual(r.returncode, 2, r.stdout)
        self.assertEqual(r.stdout, "")
        self.assertIn("bad-verdicts missing=all(", r.stderr)

    def test_one_verdict_missing_exit2_names_it(self):
        r = self.run_cli(DROP_ID="state_1")
        self.assertEqual(r.returncode, 2, r.stdout)
        self.assertEqual(r.stdout, "")
        self.assertIn("bad-verdicts missing=state_1", r.stderr)

    def test_one_malformed_verdict_exit2_names_it(self):
        r = self.run_cli(MALFORM_ID="req_1")          # a noul answered with a string
        self.assertEqual(r.returncode, 2, r.stdout)
        self.assertIn("malformed=req_1", r.stderr)
        r = self.run_cli(MALFORM_ID="state_1")        # a choice outside its options
        self.assertEqual(r.returncode, 2, r.stdout)
        self.assertIn("malformed=state_1", r.stderr)

    def test_bad_stdin_exit2(self):
        r = subprocess.run([sys.executable, os.path.join(BIN, "wrap_verdict.py")],
                           input="not json", capture_output=True, text=True)
        self.assertEqual(r.returncode, 2)

    def test_log_line_written(self):
        log = os.path.join(self.tmp, "l.jsonl")
        e = clean_env(JUDGE_CMD=f"{sys.executable} {self.fake}", JUDGE_REDACT=self.redactor,
                      CAPTURE=self.capture)
        subprocess.run([sys.executable, os.path.join(BIN, "wrap_verdict.py"), "--log", log],
                       input=json.dumps(self.ev), capture_output=True, text=True, env=e)
        row = json.loads(read(log).strip())
        self.assertEqual((row["site"], row["mode"], row["computed"]), ("wrap:verdict", "shadow", "DONE"))
        self.assertIs(row["redacted"], True)


class Status(unittest.TestCase):
    """wrap_status.sh: transcript -> wrap_evidence | wrap_verdict, plus the side effects it owns.
    HOME, WRAP_STATE_DIR and WRAP_VERDICT_LOG all point into a temp dir."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.fake, self.redactor = write_fakes(self.tmp)
        self.capture = os.path.join(self.tmp, "req.json")
        self.home = os.path.join(self.tmp, "home")
        self.state = os.path.join(self.tmp, "state")
        self.vlog = os.path.join(self.tmp, "verdict.jsonl")
        self.transcript = os.path.join(self.tmp, "t.jsonl")
        self.write_transcript(self.transcript)
        self.draft = os.path.join(self.tmp, "draft.md")
        with open(self.draft, "w") as f:
            f.write("DONE — built A\nJudge: pending\n")

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def write_transcript(self, path, sid="S1", ask="build A"):
        line = {"type": "user", "isSidechain": False, "cwd": "/w", "timestamp": "t",
                "message": {"content": ask}}
        if sid:
            line["sessionId"] = sid
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(json.dumps(line) + "\n" + assistant("DONE — built A") + "\n")

    def run_status(self, *args, **env):
        e = clean_env(HOME=self.home, JUDGE_CMD=f"{sys.executable} {self.fake}",
                      CAPTURE=self.capture, WRAP_STATE_DIR=self.state, WRAP_VERDICT_LOG=self.vlog)
        e.update(env)
        return subprocess.run([STATUS, *args], capture_output=True, text=True, env=e)

    def verdict_files(self):
        return sorted(glob.glob(os.path.join(self.state, "*.json")))

