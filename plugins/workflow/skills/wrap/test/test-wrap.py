def user(text, sidechain=False, **kw):
    return json.dumps({"type": "user", "isSidechain": sidechain, "sessionId": "S1",
                       "cwd": "/w", "timestamp": "t", "message": {"content": text}, **kw})


def tool_result(text):
    return json.dumps({"type": "user", "isSidechain": False, "cwd": "/w",
                       "message": {"content": [{"type": "tool_result", "content": text}]}})


def assistant(text=None, tools=()):
    content = ([{"type": "text", "text": text}] if text else []) + [
        {"type": "tool_use", "name": n, "input": i} for n, i in tools]
    return json.dumps({"type": "assistant", "isSidechain": False, "cwd": "/w",
                       "message": {"content": content}})


