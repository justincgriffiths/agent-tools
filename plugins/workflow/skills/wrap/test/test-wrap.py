def clean_env(**extra):
    """os.environ minus anything that could reach a real judge, a real key or real state."""
    drop = ("JUDGE_", "WRAP_", "OPENROUTER", "CLAUDE_CODE_SESSION_ID")
    e = {k: v for k, v in os.environ.items() if not k.startswith(drop)}
    e.update(extra)
    return e


def fake_key():
    """A key-SHAPED string, assembled at runtime so no key-shaped literal sits in the repo."""
    return "sk-" + "ant-" + "api03-" + "A1b2C3d4" * 5


def write_fakes(tmp):
    """Fake judge (modes via FAKE_MODE / STATE) and a fake redactor. Returns their paths."""
    fake = os.path.join(tmp, "fake-judge.py")
    with open(fake, "w") as f:
        f.write(
            "import json,sys,os\n"
            "req=json.load(sys.stdin)\n"
            "open(os.environ['CAPTURE'],'w').write(json.dumps(req))\n"
            "mode=os.environ.get('FAKE_MODE','ok')\n"
            "if mode=='fail': sys.exit(4)\n"
            "if mode=='empty': print(json.dumps({'verdicts':[]})); sys.exit(0)\n"
            "vs=[]\n"
            "for q in req['questions']:\n"
            "  t=q['type']\n"
            "  a=(0.9 if q['id'].startswith('req') else 0.0) if t=='yes_no' else 0 if t=='score' else os.environ.get('STATE','delivered-verified') if q['id'].startswith('state') else list(q['options'])[0]\n"
            "  if mode=='down': vs.append({'id':q['id'],'escalate':True,'reason':'unreachable'}); continue\n"
            "  if q['id']==os.environ.get('DROP_ID'): continue\n"
            "  if q['id']==os.environ.get('MALFORM_ID'): a='banana'\n"
            "  vs.append({'id':q['id'],'type':q['type'],'answer':a,'confidence':0.9,'escalate':False})\n"
            "print(json.dumps({'verdicts':vs,'model':'fake','latencyMs':1,'usage':{}}))\n"
            "if mode=='escalated': sys.exit(3)\n")
    redactor = os.path.join(tmp, "redact.py")
    with open(redactor, "w") as f:
        f.write("import sys; sys.stdout.write(sys.stdin.read().replace('SECRETCLIENT','<client>'))\n")
    return fake, redactor


def load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(BIN, f"{name}.py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


